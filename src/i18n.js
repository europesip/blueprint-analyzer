export function t(language, key) {
  const parts = key.split('.');
  let value = dict[language] || dict.en;
  for (const part of parts) value = value?.[part];
  return value || key;
}

export function dir(language) {
  return language === 'ar' ? 'rtl' : 'ltr';
}
